#!/usr/bin/env node
/**
 * generate-agents-md.js
 * Concatenates fetched skill content into AGENTS.md (for Codex users).
 * Run from project root: node <registry-path>/scripts/generate-agents-md.js <skill-dirs...>
 *
 * Example:
 *   node /path/to/mtel-skill-registry/scripts/generate-agents-md.js \
 *     .claude/skills/nextjs .claude/skills/tailwind .claude/skills/supabase
 */

const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const CATEGORY_ORDER = ["frontend", "backend", "database", "meta"];

function readSkillMeta(dirPath) {
  const skillPath = path.join(dirPath, "SKILL.md");
  if (!fs.existsSync(skillPath)) return null;

  const { data: meta, content } = matter(fs.readFileSync(skillPath, "utf-8"));
  return {
    name: meta.name || path.basename(dirPath),
    category: meta.category || "",
    body: content,
  };
}

const skillDirs = process.argv.slice(2);
const skills = [];

for (const dir of skillDirs) {
  const meta = readSkillMeta(dir);
  if (meta) skills.push(meta);
}

// Sort by category order, then alphabetically within category
skills.sort((a, b) => {
  const aIdx = CATEGORY_ORDER.indexOf(a.category);
  const bIdx = CATEGORY_ORDER.indexOf(b.category);
  const catDiff = (aIdx === -1 ? 99 : aIdx) - (bIdx === -1 ? 99 : bIdx);
  return catDiff !== 0 ? catDiff : a.name.localeCompare(b.name);
});

let output = `<!-- Generated by mtel-skill-registry -- do not edit manually -->\n`;
output += `<!-- sourced from mtel-skill-registry -->\n\n`;

for (const skill of skills) {
  output += `## ${skill.name}\n\n`;
  output += skill.body.trim() + "\n\n";
}

fs.writeFileSync("AGENTS.md", output);
console.log(`Generated AGENTS.md with ${skills.length} skills`);
